            <h5 class="mt-4">1. Responsable del tratamiento</h5>
            <p>Mambacode, en adelante <strong>"Mambacode"</strong>, es responsable del tratamiento de los datos personales recopilados a través de sus canales digitales, incluyendo su sitio web y formularios de contacto.</p>
            <p>Mambacode se compromete a realizar el tratamiento de los datos personales de conformidad con la legislación colombiana vigente en materia de protección de datos personales, especialmente la <strong>Ley 1581 de 2012</strong> y sus normas reglamentarias.</p>

            <h5 class="mt-4">2. Datos personales que recopilamos</h5>
            <p>A través de nuestro formulario de contacto podemos recopilar los siguientes datos personales:</p>
            <ul>
                <li>Nombre.</li>
                <li>Correo electrónico.</li>
                <li>Empresa, cuando sea suministrada.</li>
                <li>Cargo o rol, cuando sea suministrado.</li>
                <li>Número de teléfono, cuando sea suministrado.</li>
                <li>Preferencia de contacto.</li>
                <li>Asunto de la solicitud.</li>
                <li>Contenido del mensaje enviado por el usuario.</li>
            </ul>
            <p>Mambacode solicita únicamente los datos que resulten necesarios para atender y gestionar las solicitudes realizadas a través del formulario de contacto.</p>

            <h5 class="mt-4">3. Finalidades del tratamiento</h5>
            <p>Los datos personales proporcionados serán tratados para las siguientes finalidades:</p>
            <ol>
                <li>Recibir, registrar y responder las solicitudes, consultas, preguntas o mensajes enviados por los usuarios.</li>
                <li>Establecer comunicación con el usuario mediante el canal de contacto seleccionado.</li>
                <li>Solicitar información adicional cuando sea necesaria para atender adecuadamente una solicitud.</li>
                <li>Gestionar solicitudes relacionadas con nuestros servicios, productos o soluciones tecnológicas.</li>
                <li>Mantener registros de las comunicaciones realizadas con usuarios y potenciales clientes.</li>
                <li>Realizar seguimiento a solicitudes comerciales o de servicio cuando resulte pertinente.</li>
                <li>Atender requerimientos de autoridades competentes cuando exista una obligación legal.</li>
            </ol>
            <p>Los datos personales <strong>no serán utilizados para finalidades incompatibles</strong> con aquellas informadas al titular, salvo que exista una autorización adicional o una obligación legal que lo permita.</p>

            <h5 class="mt-4">4. Tratamiento del contenido de los mensajes</h5>
            <p>El usuario deberá evitar incluir en el formulario información sensible, confidencial o datos personales de terceros que no sean necesarios para realizar su solicitud.</p>
            <p>Mambacode tratará el contenido de los mensajes exclusivamente en la medida necesaria para comprender, gestionar y responder la solicitud realizada.</p>

            <h5 class="mt-4">5. Autorización del titular</h5>
            <p>Al proporcionar sus datos personales mediante el formulario de contacto, el titular autoriza a Mambacode para recolectar, almacenar, utilizar y tratar sus datos personales de acuerdo con las finalidades descritas en esta política.</p>
            <p>La autorización será solicitada mediante mecanismos que permitan evidenciar el consentimiento del titular, cuando este sea requerido.</p>
            <p>El titular podrá retirar su autorización en cualquier momento, siempre que ello no impida el cumplimiento de obligaciones legales o contractuales que resulten aplicables.</p>

            <h5 class="mt-4">6. Derechos de los titulares</h5>
            <p>De conformidad con la legislación colombiana, los titulares de los datos personales tienen derecho a:</p>
            <ul>
                <li>Conocer, actualizar y rectificar sus datos personales.</li>
                <li>Solicitar prueba de la autorización otorgada para el tratamiento de sus datos, cuando corresponda.</li>
                <li>Solicitar información sobre el uso que se ha dado a sus datos personales.</li>
                <li>Presentar consultas y reclamos relacionados con el tratamiento de sus datos.</li>
                <li>Solicitar la supresión de sus datos personales cuando sea procedente.</li>
                <li>Revocar la autorización otorgada para el tratamiento de sus datos cuando sea procedente.</li>
                <li>Acceder gratuitamente a sus datos personales que hayan sido objeto de tratamiento.</li>
            </ul>
            <p>Estos derechos podrán ejercerse de acuerdo con los procedimientos establecidos en esta política y en la legislación colombiana aplicable.</p>

            <h5 class="mt-4">7. Consultas y reclamos</h5>
            <p>El titular podrá presentar consultas o reclamos relacionados con sus datos personales utilizando los canales de contacto habilitados por Mambacode.</p>
            <p>La solicitud deberá permitir identificar al titular y describir claramente la consulta o reclamo.</p>
            <p>Mambacode dará trámite a las solicitudes de acuerdo con los términos y procedimientos establecidos en la legislación colombiana vigente.</p>

            <h5 class="mt-4">8. Seguridad de la información</h5>
            <p>Mambacode implementará medidas técnicas, administrativas y organizativas razonables destinadas a proteger los datos personales contra pérdida, adulteración, acceso no autorizado, uso indebido o divulgación no autorizada.</p>
            <p>El acceso a los datos personales estará limitado a las personas que requieran dicha información para el cumplimiento de las finalidades autorizadas o de obligaciones legales.</p>

            <h5 class="mt-4">9. Encargados y terceros</h5>
            <p>Mambacode podrá utilizar proveedores tecnológicos que actúen como encargados del tratamiento de datos personales, cuando resulte necesario para la operación de sus servicios y canales digitales.</p>
            <p>Estos terceros deberán implementar medidas apropiadas para proteger la información y tratar los datos únicamente de acuerdo con las instrucciones y finalidades autorizadas.</p>

            <h5 class="mt-4">10. Transferencia y transmisión de datos</h5>
            <p>Cuando sea necesario para la operación de los servicios tecnológicos, los datos personales podrán ser tratados mediante proveedores ubicados dentro o fuera de Colombia.</p>
            <p>En estos casos, Mambacode adoptará las medidas necesarias para garantizar que el tratamiento de los datos se realice de conformidad con la legislación colombiana aplicable y las garantías correspondientes.</p>

            <h5 class="mt-4">11. Conservación de los datos</h5>
            <p>Los datos personales serán conservados durante el tiempo que resulte necesario para cumplir las finalidades para las cuales fueron recopilados, atender solicitudes, mantener registros de las comunicaciones y cumplir obligaciones legales, contractuales o administrativas.</p>
            <p>Una vez finalizado el periodo de conservación aplicable, los datos serán eliminados, anonimizados o tratados conforme a las obligaciones legales que correspondan.</p>

            <h5 class="mt-4">12. Datos sensibles</h5>
            <p>El formulario de contacto de Mambacode no está diseñado para recopilar datos personales sensibles.</p>
            <p>Por esta razón, se solicita a los usuarios no proporcionar información relacionada con su salud, orientación sexual, información biométrica, datos relacionados con menores de edad u otra información que tenga la calidad de dato sensible, salvo que resulte estrictamente necesaria y exista un mecanismo específico que permita su tratamiento conforme a la legislación aplicable.</p>

            <h5 class="mt-4">13. Uso de cookies y tecnologías similares</h5>
            <p>El sitio web de Mambacode podrá utilizar cookies y tecnologías similares para permitir el funcionamiento del sitio, mejorar la experiencia de navegación, analizar el uso de determinadas funcionalidades y, cuando corresponda, proporcionar funcionalidades de terceros.</p>
            <p>Cuando el uso de estas tecnologías implique tratamiento de datos personales, este se realizará de acuerdo con la legislación aplicable y con las opciones de configuración disponibles para los usuarios.</p>

            <h5 class="mt-4">14. Modificaciones de esta política</h5>
            <p>Mambacode podrá actualizar esta Política de Tratamiento de Datos Personales cuando resulte necesario debido a cambios legales, regulatorios, tecnológicos u operativos.</p>
            <p>Las modificaciones serán publicadas a través de los canales digitales correspondientes.</p>

            <h5 class="mt-4">15. Vigencia</h5>
